/**
 * @brief 부저 하드웨어 클럭 및 핀 매핑 강제 활성화 (수동)
 */
void Buzzer_Init_ControllersTech(void) {
    __HAL_RCC_GPIOA_CLK_ENABLE();
    __HAL_RCC_TIM2_CLK_ENABLE();
    __HAL_RCC_AFIO_CLK_ENABLE();

    GPIO_InitTypeDef GPIO_InitStruct = {0};
    GPIO_InitStruct.Pin = GPIO_PIN_0;
    GPIO_InitStruct.Mode = GPIO_MODE_AF_PP;
    GPIO_InitStruct.Pull = GPIO_NOPULL;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOA, &GPIO_InitStruct);

    TIM2->ARR = 100 - 1;
    TIM2->CCR1 = 50;
    TIM2->CCMR1 |= (6 << TIM_CCMR1_OC1M_Pos);
    TIM2->CCER |= TIM_CCER_CC1E;
    TIM2->CR1 |= TIM_CR1_CEN;
}

/**
 * @brief 부저 주파수 실시간 변조 함수
 */
void Buzzer_Set_Frequency(uint32_t frequency) {
    if (frequency == 0) {
        TIM2->CCR1 = 0;
        return;
    }
    uint32_t timer_clock = 16000000;
    uint32_t psc_value = (timer_clock / (100 * frequency)) - 1;

    TIM2->PSC = psc_value;
    TIM2->CCR1 = 50;
}

/**
 * @brief 비상 상황 해제 시 모든 자산(LED, 부저) 즉시 클리어
 */

void System_Immediate_Clear(void) {
    // 1. 모든 LED 소등
    for (int i = 0; i < MAX_LED; i++) {
        WS28XX_SetPixel_RGB_888(&ws, i, 0x000000);
    }
    WS28XX_Update(&ws);

    // 2. 부저 소리 소거
    TIM2->CCR1 = 0;
}



